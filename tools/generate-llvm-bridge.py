#!/usr/bin/env python3
"""Developer-only: regenerate portable typed C-API adapter IR with LLVM 21.
The generated file is checked in; end-user builds never execute this script.
"""
import os
from pathlib import Path
import re
import subprocess
import tempfile
root = Path(__file__).resolve().parents[1]
llvm = Path(os.environ.get('FAZ_LLVM_HOME', '/opt/homebrew/opt/llvm@21'))
clang = os.environ.get('FAZ_BRIDGE_CLANG', str(llvm / 'bin/clang'))
with tempfile.TemporaryDirectory() as directory:
    output = Path(directory) / 'bridge.ll'
    # Clang's freestanding stdint/stddef provide fixed-width types. Skip LLVM's
    # DataTypes wrapper, which otherwise includes host-specific libc headers.
    subprocess.run([clang, '-target', 'x86_64-unknown-linux-gnu', '-ffreestanding',
                    '-DLLVM_C_DATATYPES_H', '-fno-builtin', '-fno-ident', '-fno-discard-value-names',
                    '-S', '-emit-llvm', '-O1', '-I'+str(llvm/'include'),
                    str(root/'src/runtime/platform/llvm_backend.c'), '-o', str(output)], check=True)
    text = output.read_text()
# No host triple, source paths, attributes, or module metadata enter the runtime.
# Both supported architectures use the same 64-bit C ABI scalar/pointer widths.
text = '\n'.join(line for line in text.splitlines()
                 if not line.startswith(('; ModuleID', 'source_filename', 'target ', 'attributes ', '!')))
text = re.sub(r' #\d+', '', text)
text = re.sub(r', ![a-zA-Z_.]+ !\d+', '', text)
text = re.sub(r'define dso_local (?:noundef )?i64 @rt_os_llvm_object', 'define internal i64 @rt_os_llvm_object', text)
text = text.replace('captures(none)', 'nocapture').replace('trunc nuw nsw ', 'trunc ')
text = '; Generated by tools/generate-llvm-bridge.py from llvm_backend.c.\n'+text.strip()+'\n'
(root/'src/runtime/platform/llvm_backend.ll').write_text(text)
